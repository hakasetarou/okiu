DO $$
BEGIN
    IF (SELECT COUNT(*) FROM parking_lots WHERE id IN ('lot-1', '1')) <> 1
        OR NOT EXISTS (SELECT 1 FROM parking_lots WHERE id IN ('lot-1', '1') AND capacity = 532)
    THEN
        RAISE EXCEPTION '第1駐車場の変更前の設定（532台）を確認してください。';
    END IF;
    IF (SELECT COUNT(*) FROM lot1_spot_renumbering) <> 530
        OR EXISTS (SELECT 1 FROM lot1_spot_renumbering WHERE old_number IN (7, 133))
    THEN
        RAISE EXCEPTION '第1駐車場の番号対応表を確認してください。';
    END IF;
    IF EXISTS (
        SELECT 1 FROM parking_sessions WHERE lot_id IN ('lot-1', '1') AND space_id IN (7, 133)
    ) OR EXISTS (
        SELECT 1 FROM parking_spaces
        WHERE lot_id IN ('lot-1', '1') AND spot_number IN (7, 133) AND status = 'occupied'
    ) THEN
        RAISE EXCEPTION '削除する旧7番または133番に駐車記録があります。出庫・記録の確認後に変更してください。';
    END IF;
    IF EXISTS (
        SELECT 1 FROM parking_sessions
        WHERE lot_id IN ('lot-1', '1') AND (space_id IS NULL OR space_id < 1 OR space_id > 532)
    ) OR EXISTS (
        SELECT 1 FROM parking_spaces
        WHERE lot_id IN ('lot-1', '1') AND (spot_number IS NULL OR spot_number < 1 OR spot_number > 532)
    ) THEN
        RAISE EXCEPTION '第1駐車場に想定外の枠番号があります。既存データを確認してください。';
    END IF;
END $$;

UPDATE parking_spaces p SET lot_id = l.id FROM parking_lots l
WHERE p.lot_id IN ('1', 'lot-1') AND l.id IN ('1', 'lot-1') AND p.lot_id <> l.id;
UPDATE parking_sessions s SET lot_id = l.id FROM parking_lots l
WHERE s.lot_id IN ('1', 'lot-1') AND l.id IN ('1', 'lot-1') AND s.lot_id <> l.id;

DELETE FROM parking_spaces WHERE lot_id IN ('lot-1', '1') AND spot_number IN (7, 133);

-- 一時的に負の番号へ移し、一意制約との衝突を防ぐ。
UPDATE parking_spaces SET spot_number = -spot_number WHERE lot_id IN ('lot-1', '1');
UPDATE parking_sessions SET space_id = -space_id WHERE lot_id IN ('lot-1', '1');

UPDATE parking_spaces p SET spot_number = mapping.new_number
FROM lot1_spot_renumbering mapping
WHERE p.lot_id IN ('lot-1', '1') AND p.spot_number = -mapping.old_number;
UPDATE parking_sessions s SET space_id = mapping.new_number
FROM lot1_spot_renumbering mapping
WHERE s.lot_id IN ('lot-1', '1') AND s.space_id = -mapping.old_number;

UPDATE parking_lots SET capacity = 530 WHERE id IN ('lot-1', '1');

